import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/**
 * The signed-in app is inline-styled except for a handful of semantic classes
 * (.chat-col, .chat-thread, .kpi, …) and keyframes, all defined in
 * app/globals.css next to Tailwind directives Remotion cannot compile. This
 * pulls the plain-CSS rules for every className the demo's components use —
 * plus the keyframes they reference — into one generated stylesheet.
 *
 *   node scripts/demo-css.mjs
 */
const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.join(here, "..", "..");
const root = path.join(here, "..");

const SCAN = [
  "components/chat",
  "components/rooms",
  "components/room-view.tsx",
  "components/rooms-list.tsx",
  "components/kernel-memory.tsx",
  "components/kernel-why-stuck.tsx",
  "components/cognitive-profile.tsx",
  "components/tools.tsx",
  "components/study",
  "components/school",
  "components/school-admin.tsx",
  "components/school-team.tsx",
  "components/school-insights.tsx",
  "components/raya/raya-shell.tsx",
  "components/raya/section-header.tsx",
  "components/ui",
  "components/attachment.tsx",
  "components/progress-curve.tsx",
];

function* tsFiles(dir) {
  for (const e of readdirSync(path.join(repo, dir), { withFileTypes: true })) {
    const rel = path.join(dir, e.name);
    if (e.isDirectory()) yield* tsFiles(rel);
    else if (/\.(tsx?|jsx?)$/.test(e.name)) yield rel;
  }
}

const classes = new Set();
const files = [];
for (const entry of SCAN) {
  try {
    if (entry.endsWith(".tsx") || entry.endsWith(".ts")) files.push(entry);
    else files.push(...tsFiles(entry));
  } catch {
    /* missing path — skip */
  }
}
for (const f of files) {
  const src = readFileSync(path.join(repo, f), "utf8");
  for (const m of src.matchAll(/className=(?:"([^"]+)"|\{`([^`]+)`\})/g)) {
    const raw = (m[1] ?? m[2] ?? "").split("$")[0];
    for (const c of raw.split(/\s+/)) {
      const clean = c.replace(/[^a-zA-Z0-9_-]/g, "");
      if (clean && !/^(true|false|null|undefined)$/.test(clean)) classes.add(clean);
    }
  }
}
// Classes applied conditionally / via helpers the regex misses.
for (const extra of ["is-dark", "is-foldable", "is-open", "notranslate"]) classes.add(extra);
console.log(`${classes.size} classes used across ${files.length} files`);

const css = readFileSync(path.join(repo, "app", "globals.css"), "utf8");
// Split top-level rules (handles one level of nesting: @media / @keyframes).
const rules = [];
let depth = 0;
let start = 0;
for (let i = 0; i < css.length; i++) {
  if (css[i] === "{") depth++;
  else if (css[i] === "}") {
    depth--;
    if (depth === 0) {
      rules.push(css.slice(start, i + 1));
      start = i + 1;
    }
  }
}
const wanted = [];
const keyframes = new Set();
for (const rule of rules) {
  const head = rule.slice(0, rule.indexOf("{")).trim();
  if (!head || head.startsWith("@tailwind") || head.startsWith("@apply")) continue;
  if (head.startsWith("@keyframes")) {
    keyframes.add(head.split(/\s+/)[1]);
    wanted.push({ head, rule, keyframe: head.split(/\s+/)[1] });
    continue;
  }
  const hits = [...head.matchAll(/\.([a-zA-Z0-9_-]+)/g)].map((m) => m[1]);
  if (hits.some((h) => classes.has(h))) wanted.push({ head, rule });
}
// Keep only keyframes referenced by kept rules (or the known welcome ones).
const kept = wanted.filter((w) => !w.keyframe);
const keptText = kept.map((w) => w.rule).join("\n");
const usedFrames = new Set(
  [...keptText.matchAll(/animation[^;]*\b([a-zA-Z][\w-]*)\b/g)]
    .map((m) => m[1])
    .filter((n) => !/^(ease|linear|infinite|both|forwards|none|normal|reverse|alternate|cubic-bezier|steps|initial|inherit|unset|s|ms)/.test(n)),
);
for (const extra of ["writeReveal", "floatSm", "shineSweep", "fadeUp", "pulseSoft"]) usedFrames.add(extra);
for (const w of wanted) {
  if (w.keyframe && usedFrames.has(w.keyframe)) kept.push(w);
}
const out = [
  "/* Generated by scripts/demo-css.mjs — plain-CSS rules for the demo's app components. */",
  ...kept.map((w) => w.rule),
].join("\n");
const dir = path.join(root, "src", "demo", "generated");
mkdirSync(dir, { recursive: true });
writeFileSync(path.join(dir, "app.css"), out);
console.log(`${kept.length} rules → src/demo/generated/app.css (${(out.length / 1024).toFixed(0)} KB)`);
