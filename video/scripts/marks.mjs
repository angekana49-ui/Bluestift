import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * The brand marks, read from the site's public/ and compiled into the bundle
 * as data URIs (src/generated/marks.ts).
 *
 * In the bundle rather than served: a render serves public/ from a temporary
 * copy, and halfway through a two-hour render that copy once lost the files at
 * its root — every mark 404'd and the render was cancelled. A quarter of a
 * megabyte travels better inside the code.
 *
 *   node scripts/marks.mjs
 */
const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "..", "..");
const video = join(here, "..");

const marks = ["raya-mark.png", "raya-mark-dark.png", "icon-512.png", "icon-raya-512.png"];
const dataUri = (file) => `data:image/png;base64,${readFileSync(join(repo, "public", file)).toString("base64")}`;
const out = join(video, "src", "generated", "marks.ts");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// Generated by scripts/marks.mjs — do not edit.\n` +
    `export const MARKS: Record<string, string> = {\n` +
    marks.map((m) => `  ${JSON.stringify(m)}: "${dataUri(m)}",\n`).join("") +
    `};\n`,
);
console.log(`${marks.length} marks → src/generated/marks.ts`);
